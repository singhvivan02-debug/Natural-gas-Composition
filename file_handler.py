"""
================================================================================
 NATURAL GAS DATA TRANSFORMATION AND COMPILATION SYSTEM
================================================================================
 Module       : file_handler.py
 Description  : This module implements all file I/O for the application:

                    1. CSV Import  - reads a user-supplied CSV file
                       (manually prepared, exported from a lab LIMS
                       system, or a template generated by this very
                       application) and converts it into a validated
                       GasComposition object via gas_data.py.

                    2. CSV Export  - writes the current gas composition,
                       the full set of calculated engineering results
                       (from calculations.py), or both together as a
                       single professional "compilation report" CSV file
                       that a user can archive, print, or share.

                    3. CSV Template Generation - produces a correctly
                       headed, empty CSV file that a user can fill out in
                       Excel and re-import, guaranteeing column-name
                       compatibility with the importer.

                All operations are wrapped in structured result objects
                (ImportResult / ExportResult) rather than raising bare
                exceptions up into the GUI layer, so gui.py can always
                display a clean, professional message dialog regardless
                of what went wrong (missing file, bad permissions,
                malformed CSV, wrong columns, empty file, etc.).

 Author       : Semester Project
 Version      : 1.0.0
================================================================================
"""

import os
import csv
import logging
from dataclasses import dataclass, field
from datetime import datetime
from typing import List, Optional

import pandas as pd

from gas_data import GasComposition, validate_composition
from calculations import CalculationResults

logger = logging.getLogger(__name__)


# ==============================================================================
# 1. CONSTANTS
# ==============================================================================
CSV_FILETYPES = [("CSV Files", "*.csv"), ("All Files", "*.*")]

# Column headers written by export_composition_to_csv() / expected (in a
# case-insensitive, flexible manner - see gas_data._find_matching_column)
# by import_composition_from_csv().
COMPOSITION_CSV_COLUMNS = [
    "Component",
    "Formula",
    "Mole (%)",
    "Molecular Weight (lb/lb-mol)",
    "Gross Heating Value (Btu/scf)",
    "Critical Temp (R)",
    "Critical Pressure (psia)",
]

REPORT_TITLE = "NATURAL GAS DATA TRANSFORMATION AND COMPILATION REPORT"


# ==============================================================================
# 2. RESULT CONTAINERS
# ==============================================================================
@dataclass
class ImportResult:
    """
    Structured outcome of a CSV import operation, returned to the GUI so
    it can react appropriately (populate the table, show warnings, or
    display a clear error dialog) without needing to catch exceptions.
    """
    success: bool
    composition: Optional[GasComposition] = None
    warnings: List[str] = field(default_factory=list)
    error_message: str = ""
    source_filepath: str = ""
    rows_read: int = 0


@dataclass
class ExportResult:
    """Structured outcome of any CSV export operation."""
    success: bool
    filepath: str = ""
    error_message: str = ""


# ==============================================================================
# 3. UTILITY HELPERS
# ==============================================================================
def timestamped_filename(prefix: str, extension: str = "csv") -> str:
    """
    Builds a default filename such as 'gas_composition_2026-08-30_142310.csv',
    used to pre-fill the GUI's Save-As dialog so users aren't forced to
    think of a filename every time they export.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d_%H%M%S")
    return f"{prefix}_{timestamp}.{extension}"


def _safe_open_check(filepath: str) -> Optional[str]:
    """
    Performs pre-flight checks common to both import and export before
    touching the filesystem, returning a human-readable error message if
    a problem is detected, or None if everything looks fine.
    """
    directory = os.path.dirname(os.path.abspath(filepath))
    if directory and not os.path.isdir(directory):
        return f"The target folder does not exist:\n{directory}"
    return None


# ==============================================================================
# 4. CSV IMPORT
# ==============================================================================
def import_composition_from_csv(filepath: str) -> ImportResult:
    """
    Reads a CSV file from disk and converts it into a GasComposition.

    Handles, with clear and specific messages, the most common failure
    modes an end user will encounter:
        - File does not exist / path is invalid
        - File exists but is empty
        - File is not valid CSV (parser errors)
        - File is valid CSV but missing the required 'Component' /
          'Mole (%)' columns (delegated to gas_data.from_dataframe, which
          also handles a variety of acceptable header-name synonyms)
        - Encoding issues (falls back from utf-8-sig to latin-1)

    Returns:
        ImportResult describing the outcome.
    """
    if not filepath:
        return ImportResult(success=False, error_message="No file was selected.")

    if not os.path.isfile(filepath):
        return ImportResult(
            success=False,
            error_message=f"The selected file could not be found:\n{filepath}",
            source_filepath=filepath,
        )

    if os.path.getsize(filepath) == 0:
        return ImportResult(
            success=False,
            error_message="The selected file is empty and contains no data.",
            source_filepath=filepath,
        )

    # --- Attempt to read the CSV, trying a couple of common encodings ---
    dataframe = None
    read_error = None
    for encoding in ("utf-8-sig", "utf-8", "latin-1"):
        try:
            dataframe = pd.read_csv(filepath, encoding=encoding)
            read_error = None
            break
        except UnicodeDecodeError as exc:
            read_error = exc
            continue
        except pd.errors.EmptyDataError:
            return ImportResult(
                success=False,
                error_message="The CSV file has no columns to parse (it appears empty).",
                source_filepath=filepath,
            )
        except pd.errors.ParserError as exc:
            return ImportResult(
                success=False,
                error_message=f"The file is not a valid CSV file and could not be parsed.\n\n"
                              f"Technical details: {exc}",
                source_filepath=filepath,
            )
        except Exception as exc:
            read_error = exc
            continue

    if dataframe is None:
        return ImportResult(
            success=False,
            error_message=f"Could not read the file due to an encoding or format issue.\n\n"
                          f"Technical details: {read_error}",
            source_filepath=filepath,
        )

    if dataframe.empty or len(dataframe.columns) == 0:
        return ImportResult(
            success=False,
            error_message="The CSV file was read successfully but contains no usable rows.",
            source_filepath=filepath,
        )

    # --- Delegate the actual column-matching / row parsing to gas_data ---
    composition, warnings = GasComposition.from_dataframe(dataframe)

    if not composition.components or composition.total_mole_percent() == 0.0:
        return ImportResult(
            success=False,
            error_message=(
                "No valid gas composition data could be extracted from this file.\n\n"
                "Please ensure the CSV contains a 'Component' column and a "
                "'Mole (%)' column (a downloadable template is available from "
                "the File menu)."
            ),
            warnings=warnings,
            source_filepath=filepath,
        )

    logger.info("Imported composition from '%s' (%d rows, total=%.2f%%, %d warnings).",
                filepath, len(dataframe), composition.total_mole_percent(), len(warnings))

    return ImportResult(
        success=True,
        composition=composition,
        warnings=warnings,
        source_filepath=filepath,
        rows_read=len(dataframe),
    )


# ==============================================================================
# 5. CSV EXPORT — COMPOSITION ONLY
# ==============================================================================
def export_composition_to_csv(composition: GasComposition, filepath: str) -> ExportResult:
    """
    Exports the raw gas composition table (one row per component,
    including inactive/zero-percent components) to a CSV file, using the
    same column layout the importer expects, so an exported file can be
    re-imported without modification.
    """
    preflight_error = _safe_open_check(filepath)
    if preflight_error:
        return ExportResult(success=False, error_message=preflight_error)

    try:
        df = composition.to_dataframe()
        df.to_csv(filepath, index=False, encoding="utf-8-sig")
        logger.info("Composition exported to: %s (%d rows)", filepath, len(df))
        return ExportResult(success=True, filepath=filepath)
    except PermissionError:
        return ExportResult(
            success=False,
            error_message=(
                f"Permission denied while writing to:\n{filepath}\n\n"
                "The file may be open in another program (e.g. Excel). "
                "Please close it and try again."
            ),
        )
    except Exception as exc:
        logger.error("Failed to export composition to '%s': %s", filepath, exc)
        return ExportResult(success=False, error_message=f"Export failed: {exc}")


# ==============================================================================
# 6. CSV EXPORT — FULL ENGINEERING REPORT (composition + calculated results)
# ==============================================================================
def export_full_report_to_csv(composition: GasComposition,
                                results: CalculationResults,
                                filepath: str,
                                sample_id: str = "",
                                operator_name: str = "") -> ExportResult:
    """
    Writes a single, professionally formatted CSV "compilation report"
    containing three sections in one file:

        SECTION 1 - Report metadata (title, date/time, sample ID, operator)
        SECTION 2 - Full gas composition table (every component)
        SECTION 3 - Calculated engineering results (MW, SG, HV, Z, density)

    This mirrors the layout of a real laboratory PVT report and is the
    file a student would submit or print as the project's "Export
    Results" deliverable.
    """
    preflight_error = _safe_open_check(filepath)
    if preflight_error:
        return ExportResult(success=False, error_message=preflight_error)

    try:
        with open(filepath, mode="w", newline="", encoding="utf-8-sig") as csv_file:
            writer = csv.writer(csv_file)

            # --- Section 1: Metadata ---
            writer.writerow([REPORT_TITLE])
            writer.writerow([])
            writer.writerow(["Report Generated:", datetime.now().strftime("%Y-%m-%d %H:%M:%S")])
            writer.writerow(["Sample ID:", sample_id or "N/A"])
            writer.writerow(["Operator / Engineer:", operator_name or "N/A"])
            writer.writerow(["Operating Pressure (psia):", f"{results.operating_pressure_psia:.2f}"])
            writer.writerow(["Operating Temperature (F):", f"{results.operating_temperature_F:.2f}"])
            writer.writerow([])

            # --- Section 2: Gas Composition Table ---
            writer.writerow(["GAS COMPOSITION"])
            writer.writerow(COMPOSITION_CSV_COLUMNS)
            for comp in composition.components:
                row = comp.to_dict()
                writer.writerow([row[col] for col in COMPOSITION_CSV_COLUMNS])
            writer.writerow(["TOTAL", "", f"{composition.total_mole_percent():.3f}", "", "", "", ""])
            writer.writerow([])

            # --- Section 3: Calculated Engineering Results ---
            writer.writerow(["CALCULATED RESULTS"])
            writer.writerow(["Property", "Value"])
            for label, value in results.as_flat_dict().items():
                writer.writerow([label, value])

            if results.warnings:
                writer.writerow([])
                writer.writerow(["ENGINEERING NOTES / WARNINGS"])
                for warning_text in results.warnings:
                    writer.writerow([warning_text])

        logger.info("Full engineering report exported to: %s", filepath)
        return ExportResult(success=True, filepath=filepath)

    except PermissionError:
        return ExportResult(
            success=False,
            error_message=(
                f"Permission denied while writing to:\n{filepath}\n\n"
                "The file may be open in another program (e.g. Excel). "
                "Please close it and try again."
            ),
        )
    except Exception as exc:
        logger.error("Failed to export full report to '%s': %s", filepath, exc)
        return ExportResult(success=False, error_message=f"Export failed: {exc}")


# ==============================================================================
# 7. CSV TEMPLATE GENERATION
# ==============================================================================
def generate_import_template_csv(filepath: str) -> ExportResult:
    """
    Writes an empty, correctly-headed CSV template (using every standard
    component name pre-filled in the first column with a blank Mole (%)
    column) so a user can open it in Excel, fill in percentages, save,
    and re-import it with guaranteed column compatibility.
    """
    preflight_error = _safe_open_check(filepath)
    if preflight_error:
        return ExportResult(success=False, error_message=preflight_error)

    try:
        from gas_data import STANDARD_COMPONENT_LIBRARY

        with open(filepath, mode="w", newline="", encoding="utf-8-sig") as csv_file:
            writer = csv.writer(csv_file)
            writer.writerow(["Component", "Mole (%)"])
            for comp in STANDARD_COMPONENT_LIBRARY:
                writer.writerow([comp.name, ""])

        logger.info("Import template generated at: %s", filepath)
        return ExportResult(success=True, filepath=filepath)

    except Exception as exc:
        logger.error("Failed to generate template at '%s': %s", filepath, exc)
        return ExportResult(success=False, error_message=f"Could not create template: {exc}")
